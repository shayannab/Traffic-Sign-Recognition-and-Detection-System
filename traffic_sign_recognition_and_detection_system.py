# --- Preprocessing and Augmentation Functions ---

def preprocess_image(image, label):
    # Convert image to float32 and normalize to [0, 1]
    image = tf.cast(image, tf.float32) / 255.0
    return image, label

# Data augmentation layers (TensorFlow native)
# These layers will be applied to the training data only
data_augmentation = tf.keras.Sequential([
    tf.keras.layers.RandomRotation(factor=0.1),
    tf.keras.layers.RandomZoom(height_factor=0.1, width_factor=0.1),
    tf.keras.layers.RandomBrightness(factor=0.2),
    # No RandomFlip or RandomContrast as traffic signs should maintain their orientation and specific colors
])

def augment_image(image, label):
    # Apply augmentation to the image
    image = data_augmentation(image, training=True)
    return image, label

print("Preprocessing and augmentation functions defined.")

# --- Handle Class Imbalance with Class Weights ---
from sklearn.utils import class_weight

# Calculate class weights for the training data
