# --- Modular Inference Pipeline ---
def traffic_sign_detection_pipeline(image_path_or_url, detection_threshold=0.5):

    start_time = time.time()

    # 1. Load the input image
    if image_path_or_url.startswith('http'):
        response = requests.get(image_path_or_url)
        image_orig = Image.open(BytesIO(response.content)).convert('RGB')
    else:
        image_orig = Image.open(image_path_or_url).convert('RGB')

    image_np = np.array(image_orig)

    print(f"Processing image of size: {image_np.shape[1]}x{image_np.shape[0]}")

    # 2. Perform object detection
    # Replace mock_object_detector with your actual detector model.predict(image_np[tf.newaxis, ...])
    detected_objects = mock_object_detector(image_np) # This would be detector(tf.constant(image_np))[output_keys]

    classified_signs = []

    # 3. Iterate through detections, crop, and classify
    for obj in detected_objects:
        ymin, xmin, ymax, xmax = obj['box']
        score = obj['score']

        if score >= detection_threshold:
            # Crop the detected region
            cropped_sign = image_np[ymin:ymax, xmin:xmax]

            # Resize for our classifier
            resized_sign = cv2.resize(cropped_sign, (IMG_WIDTH, IMG_HEIGHT))

            # Preprocess for classifier (normalize and add batch dimension)
            preprocessed_sign = tf.cast(resized_sign, tf.float32) / 255.0
            preprocessed_sign = np.expand_dims(preprocessed_sign, axis=0) # Add batch dimension

            # Classify the sign
            prediction = classifier_model.predict(preprocessed_sign, verbose=0)
            predicted_class_id = np.argmax(prediction, axis=1)[0]

            classified_signs.append({
                'box': obj['box'],
                'detection_score': score,
                'predicted_class_id': predicted_class_id,
                'classification_confidence': np.max(prediction)
            })

    end_time = time.time()
    inference_time = end_time - start_time
    print(f"Inference completed in {inference_time:.4f} seconds.")

    return classified_signs, inference_time


