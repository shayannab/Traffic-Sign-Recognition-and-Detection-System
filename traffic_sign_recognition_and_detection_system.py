# --- Load images and labels ---
def load_gtsrb_data(data_dir):
    images = []
    labels = []
    if not os.path.exists(data_dir):
        raise FileNotFoundError(f"Data directory does not exist: {data_dir}")
    if not os.path.isdir(data_dir):
        raise NotADirectoryError(f"Path is not a directory: {data_dir}")

    # Loop through each class folder (00000, 00001, ...)
    for class_folder_name in sorted(os.listdir(data_dir)):
        class_folder_path = os.path.join(data_dir, class_folder_name)
        # Ensure it's a directory and its name is a number (e.g., '00000')
        if os.path.isdir(class_folder_path) and class_folder_name.isdigit():
            label = int(class_folder_name)
            for img_file_name in os.listdir(class_folder_path):
                # Filter out non-image files, like 'GT-*.csv'
                if img_file_name.lower().endswith(('.ppm', '.png', '.jpg', '.jpeg')):
                    img_path = os.path.join(class_folder_path, img_file_name)
                    try:
                        img = cv2.imread(img_path)
                        if img is None:
                            print(f"Warning: Could not read image {img_path}. Skipping.")
                            continue
                        img = cv2.resize(img, (IMG_WIDTH, IMG_HEIGHT))
                        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB) # Convert BGR to RGB
                        images.append(img)
                        labels.append(label)
                    except Exception as e:
                        print(f"Error processing image {img_path}: {e}")
        elif os.path.isdir(class_folder_path) and not class_folder_name.isdigit():
            print(f"Skipping non-digit directory in {data_dir}: {class_folder_name}")

    return np.array(images), np.array(labels)

